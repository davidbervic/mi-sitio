// Reads articles-meta.json + each article's JSON-LD, outputs articles-data.js
// Run: node generate-articles.js
// Netlify runs this automatically on every deploy.

const fs   = require('fs');
const path = require('path');

const SITE_DIR   = __dirname;
const META_FILE  = path.join(SITE_DIR, 'articles-meta.json');
const OUT_FILE   = path.join(SITE_DIR, 'articles-data.js');
const POPULAR_FILE = path.join(SITE_DIR, 'articles-popular.json');

const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

function isoToDisplay(iso) {
  // "2026-10-06" → "Oct 6, 2026"
  const parts = iso.split('-');
  if (parts.length !== 3) return iso;
  const [year, month, day] = parts;
  return `${MONTHS[parseInt(month, 10) - 1]} ${parseInt(day, 10)}, ${year}`;
}

function extractFromHtml(filepath) {
  let html;
  try {
    html = fs.readFileSync(filepath, 'utf8');
  } catch (e) {
    console.warn(`  Warning: could not read ${filepath}`);
    return null;
  }

  // Find all JSON-LD blocks
  const ldRe = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g;
  let articleLd = null;
  let m;
  while ((m = ldRe.exec(html)) !== null) {
    try {
      const parsed = JSON.parse(m[1]);
      if (parsed['@type'] === 'Article') { articleLd = parsed; break; }
    } catch (e) {}
  }

  if (!articleLd) {
    // Fallback: grab meta description and og:image
    const descMatch  = html.match(/<meta name="description" content="([^"]+)"/);
    const imageMatch = html.match(/<meta property="og:image" content="https?:\/\/[^/]+\/([^"]+)"/);
    const titleMatch = html.match(/<title>([^<]+)<\/title>/);
    return {
      title: titleMatch  ? titleMatch[1].replace(/\s*·\s*Muvap$/, '').trim() : '',
      quick: descMatch   ? descMatch[1] : '',
      date:  '',
      author: 'Muvap',
      img:   imageMatch  ? imageMatch[1] : null,
    };
  }

  return {
    title:  articleLd.headline    || '',
    quick:  articleLd.description || '',
    date:   articleLd.datePublished ? isoToDisplay(articleLd.datePublished) : '',
    author: (articleLd.author && articleLd.author.name) ? articleLd.author.name : 'Muvap',
    img:    articleLd.image || null,
  };
}

// Load the minimal meta list (id, category, readTime, optionally featured/bullets)
const metaList = JSON.parse(fs.readFileSync(META_FILE, 'utf8'));

// Load popular searches if the file exists, otherwise use defaults
let popular = [
  { label: 'What is lead scoring',        query: 'lead scoring' },
  { label: 'Fit score vs engagement score', query: 'fit score'  },
  { label: 'CRM comparison',              query: 'crms'         },
  { label: 'Lifecycle stages',            query: 'lifecycle'    },
];
if (fs.existsSync(POPULAR_FILE)) {
  try { popular = JSON.parse(fs.readFileSync(POPULAR_FILE, 'utf8')); } catch (e) {}
}

const articles = metaList.map(meta => {
  const htmlPath = path.join(SITE_DIR, meta.href);
  const ex = extractFromHtml(htmlPath);

  const entry = {
    id:       meta.id,
    category: meta.category,
    href:     meta.href,
    title:    (ex && ex.title)  ? ex.title  : (meta.title  || ''),
    quick:    (ex && ex.quick)  ? ex.quick  : (meta.quick  || ''),
    author:   (ex && ex.author) ? ex.author : 'Muvap',
    date:     (ex && ex.date)   ? ex.date   : (meta.date   || ''),
    readTime: meta.readTime,
  };

  if (meta.featured) entry.featured = true;
  if (meta.bullets)  entry.bullets  = meta.bullets;

  const img = (ex && ex.img) ? ex.img : (meta.img || null);
  if (img) entry.img = img;

  return entry;
});

// Serialize
function esc(s) { return JSON.stringify(s); }

const lines = articles.map(a => {
  const parts = [`id: ${esc(a.id)}`];
  if (a.featured) parts.push('featured: true');
  parts.push(`category: ${esc(a.category)}`);
  parts.push(`href: ${esc(a.href)}`);
  parts.push(`title: ${esc(a.title)}`);
  parts.push(`quick: ${esc(a.quick)}`);
  if (a.bullets) parts.push(`bullets: ${JSON.stringify(a.bullets)}`);
  parts.push(`author: ${esc(a.author)}`);
  parts.push(`date: ${esc(a.date)}`);
  parts.push(`readTime: ${esc(a.readTime)}`);
  if (a.img) parts.push(`img: ${esc(a.img)}`);
  return `  { ${parts.join(', ')} }`;
});

const popularLines = popular.map(p => `  { label: ${esc(p.label)}, query: ${esc(p.query)} }`);

const output =
  `// AUTO-GENERATED by generate-articles.js — do not edit by hand.\n` +
  `// Edit articles-meta.json to add or update articles.\n` +
  `var MUVAP_ARTICLES = [\n${lines.join(',\n')},\n];\n\n` +
  `var MUVAP_POPULAR = [\n${popularLines.join(',\n')},\n];\n`;

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Generated articles-data.js with ${articles.length} articles.`);
